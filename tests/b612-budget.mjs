import assert from 'node:assert/strict';
import {budgetPage,budgetTotals} from '../supabase/functions/job-finance/b612-budget.mjs';
const text='N° 123456\n$ TOTAL SIN IVA 116,135.42\n$ TOTAL CON IVA 140,523.86';
assert.deepEqual(budgetTotals(text,'123456'),{net:116135.42,gross:140523.86,vat:24388.44,budgetCode:'123456'});
assert.throws(()=>budgetTotals(text,'12345'),/corresponde/);
assert.throws(()=>budgetTotals(text+'\nTOTAL SIN IVA 20.00','123456'),/único/);
assert.throws(()=>budgetTotals(text.replace('140,523.86','100.00'),'123456'),/consistentes/);
assert.throws(()=>budgetTotals(text.replace('116,135.42','116.135,42'),'123456'),/Formato/);
const line=await budgetPage({getTextContent:async()=>({items:[{str:'140.00',transform:[0,0,0,0,100,20]},{str:'TOTAL CON IVA',transform:[0,0,0,0,10,20]},{str:'N° 123456',transform:[0,0,0,0,10,80]},{str:'100.00',transform:[0,0,0,0,100,40]},{str:'TOTAL SIN IVA',transform:[0,0,0,0,10,40]}]})});
assert.equal(budgetTotals(line,'123456').net,100);assert.equal(budgetTotals(line,'123456').gross,140);
console.log('PASS B612 PDF visual text order, exact code, separate net/VAT/total, ambiguous values and invalid totals.');
